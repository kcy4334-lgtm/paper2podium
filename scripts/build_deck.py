# -*- coding: utf-8 -*-
"""`slides.yaml` -> `talk.tex` (Beamer + metropolis).

    python scripts/build_deck.py slides.yaml -o out/talk.tex
    cd out && pdflatex talk.tex && pdflatex talk.tex     # twice: page numbers, progress bar

Why Beamer
  If the paper is LaTeX, this uses the same engine, the same figure files,
  the same symbols. With no conversion step, a transcription accident in a
  figure, a formula, or a minus sign structurally cannot happen. The output
  is a single PDF, so it comes out identical even when the venue PC has no
  matching font.

Traps built in here (every one of these actually happened)
  - `\\begin{frame}[standout]` gets its next line eaten as the frametitle if
    that line starts with `{` -> put `\\vspace{0pt}` before the first line.
  - Without `block=fill` the block has no background, and under `block=fill`
    a block with no title becomes an empty gray band -> a block always gets
    a title.
  - pdflatex + cmss is a bitmap font, so there is no 40pt: the minus sign
    next to a big number stretches out like an em dash -> `lmodern` +
    `\\bigminus` (a hand-drawn bar).
  - A figure that gets cropped needs both `max width` and `max height` given
    together. Giving only one lets it overflow.
"""
