# The typesetting engine. Chosen with `meta.engine`. Default is `pdflatex`.
#
#   Before this existed, the preamble was a module constant with
#   `\usepackage[T1]{fontenc}` hard-coded in. So building a deck from a
#   non-Latin-script manuscript would not compile, and the advice the builder
#   left was "use XeLaTeX," except there was no way to do that. The only
#   path left was hand-editing the generated `.tex`, exactly what this skill
#   forbids in section 1. Advice with no way to act on it is not advice, it
#   is a dead end.
#
#   Choosing `xelatex` sets up `fontspec` and a CJK font. `meta.cjk_font`
#   changes the font name (default Malgun Gothic, Windows's default Hangul font).
ENGINES = {
    "pdflatex": (r"""\usepackage{lmodern}      %% cmss is a bitmap font, so the minus sign gets mangled at large sizes
\usepackage[T1]{fontenc}  %% without it, OT1 prints `<` as an inverted exclamation mark and `>` as an inverted question mark"""),
    "xelatex": (r"""%% XeLaTeX typesets non-ASCII (Hangul, kana, Han characters) directly.
%%   `fontenc` and `lmodern` are not used (they are for an 8-bit engine and would hurt here).
%% It's `kotex`, not `xeCJK`. Following Chinese/Japanese convention, xeCJK eats
%%   the space between characters, but Korean uses spacing between words.
%%   Typesetting it for real, xeCJK ran a Korean sentence together into one
%%   unspaced word ("무엇을구축했나"), and `CJKspace=true` did not fix it
%%   either. kotex keeps the spacing as-is.
\usepackage{fontspec}
\usepackage{kotex}
\setmainhangulfont{%(cjkfont)s}
\setsanshangulfont{%(cjkfont)s}
\setmonohangulfont{%(cjkfont)s}"""),
}

